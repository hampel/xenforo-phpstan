<?php

declare(strict_types=1);

namespace Hampel\XenForo\PHPStan\Generator;

use DateTimeImmutable;
use DateTimeZone;
use FilesystemIterator;
use Hampel\XenForo\PHPStan\Classes;
use RecursiveCallbackFilterIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;

/**
 * Writes what PHPStan cannot learn from the forum's source alone.
 *
 * XenForo 2.3 renamed classes with type suffixes - Tools became ToolsController - and aliases
 * each old name at runtime, through an autoloader that calls class_alias(). PHPStan cannot
 * follow that, so an add-on that extends or type-hints a legacy name sees every inherited
 * member as undefined. The forum itself is asked which names it aliases (\XF::getAliasForClass()
 * over every class file), so the stub cannot disagree with the install it was generated against:
 * a filename rule misses the six suffixes the mapping table abbreviates and invents names core
 * never aliases.
 *
 * A class extension's parent, XFCP_<Name>, exists only at runtime too. XenForo writes a hint
 * file for an add-on in development mode, but a packaged add-on ships without one, and the
 * methods an installed add-on's extensions add are reachable from any other add-on. So the hint
 * is regenerated here for every class extension the install declares, from the committed
 * _data/class_extensions.xml files - no database.
 */
final class Generator
{
    public const ALIASES_STUB = 'legacy-aliases.stub.php';
    public const EXTENSIONS_STUB = 'class-extensions.stub.php';
    public const CLASSES = 'classes.php';

    /**
     * A runtime alias need not be a declarable class name: 43 of XenForo 2.3.13's strip to
     * `Abstract`. class_alias() accepts it; a source declaration is a parse error. Skipping them
     * costs nothing, because no add-on source could have referenced one either.
     */
    private const RESERVED = [
        'abstract', 'and', 'array', 'as', 'break', 'callable', 'case', 'catch', 'class', 'clone',
        'const', 'continue', 'declare', 'default', 'die', 'do', 'echo', 'else', 'elseif', 'empty',
        'enddeclare', 'endfor', 'endforeach', 'endif', 'endswitch', 'endwhile', 'enum', 'exit',
        'extends', 'final', 'finally', 'fn', 'for', 'foreach', 'function', 'global', 'goto', 'if',
        'implements', 'include', 'include_once', 'instanceof', 'insteadof', 'interface', 'isset',
        'list', 'match', 'namespace', 'new', 'or', 'parent', 'print', 'private', 'protected',
        'public', 'readonly', 'require', 'require_once', 'return', 'self', 'static', 'switch',
        'throw', 'trait', 'try', 'unset', 'use', 'var', 'while', 'xor', 'yield',
    ];

    /** Directories under an add-on that hold no add-on classes. */
    private const SKIPPED = ['vendor', 'node_modules', '_build', '_data', '_output', '_releases', '_no_upload'];

    /** @var array<string, string> class => the file its name was derived from */
    private array $files = [];

    public function __construct(
        private readonly string $root,
    ) {
    }

    public static function isForum(string $root): bool
    {
        return is_file($root . '/src/XF.php') && is_dir($root . '/src/XF');
    }

    public function generate(string $out): Summary
    {
        if (! self::isForum($this->root)) {
            throw new RuntimeException(sprintf('%s is not a XenForo root: no src/XF.php.', $this->root));
        }

        $this->boot();

        $aliases = $this->aliases();
        $extensions = [];
        foreach ($this->extensionFiles() as $file) {
            // The add-on id is the path under src/addons: Vendor/AddOn, or a single segment.
            $addon = substr(dirname($file, 2), strlen($this->root . '/src/addons/'));
            foreach (ClassExtension::fromXmlFiles([$file]) as $extension) {
                $extensions[] = [$extension, $addon];
            }
        }

        $header = [
            'GENERATED by vendor/bin/xenforo-phpstan - do not edit, and do not commit.',
            sprintf('XenForo %d at %s, generated %s.', \XF::$versionId, $this->root, $this->now()),
            'Regenerate after upgrading XenForo or changing a class extension: a stale file',
            'fails as a flood of undefined-method errors naming classes that were renamed.',
        ];

        $aliasStub = new Stub();
        $skipped = [];
        $abstract = 0;
        foreach ($aliases as $alias => $class) {
            $pos = strrpos($alias, '\\');
            $namespace = substr($alias, 0, (int) $pos);
            $short = substr($alias, $pos + 1);

            if (! self::declarable($short)) {
                $skipped[] = $alias;

                continue;
            }

            $shape = $this->shape($class);
            if ($shape === null) {
                $skipped[] = $alias;

                continue;
            }

            if ($shape === 'abstract class') {
                $abstract++;
            }

            $aliasStub->add($namespace, sprintf('%s %s extends \\%s {}', $shape, $short, $class));
        }

        $extensionStub = new Stub();
        $map = [];
        $legacy = 0;
        foreach ($extensions as [$extension, $addon]) {
            $hint = $extension->hintClass();
            $pos = strrpos($hint, '\\');
            $extensionStub->add(
                substr($hint, 0, (int) $pos),
                sprintf('class %s extends \\%s {}', substr($hint, $pos + 1), $extension->fromClass),
            );

            // Extension::extendClass() normalises the registered name through
            // \XF::getClassForAlias(), so an extension of a legacy name applies to the renamed
            // class. The map is keyed the same way.
            $resolved = \XF::getClassForAlias($extension->fromClass);
            if ($resolved !== $extension->fromClass) {
                $legacy++;
            }

            $map[$resolved][] = ['class' => $extension->toClass, 'addon' => $addon];
        }
        ksort($map);

        if (! is_dir($out) && ! @mkdir($out, 0775, true)) {
            throw new RuntimeException(sprintf('Could not create %s.', $out));
        }

        $this->write($out . '/' . self::ALIASES_STUB, $aliasStub->render([
            ...$header,
            sprintf('Source: \XF::getAliasForClass() over src/XF and src/addons. %d aliases, %d skipped as undeclarable names.', $aliasStub->count(), count($skipped)),
        ]));
        $this->write($out . '/' . self::EXTENSIONS_STUB, $extensionStub->render([
            ...$header,
            sprintf('Source: every _data/class_extensions.xml under src/addons. %d class extensions.', $extensionStub->count()),
        ]));
        $this->write($out . '/' . self::CLASSES, "<?php\n\n// " . implode("\n// ", $header) . "\n\nreturn " . var_export([
            'format' => Classes::FORMAT,
            'xenforo' => ['versionId' => \XF::$versionId, 'root' => $this->root],
            'generated' => $this->now(),
            'aliases' => $aliases,
            'extensions' => $map,
        ], true) . ";\n");

        return new Summary(
            versionId: \XF::$versionId,
            aliases: $aliasStub->count(),
            abstractAliases: $abstract,
            skippedAliases: $skipped,
            extensions: $extensionStub->count(),
            legacyExtensions: $legacy,
            extendedClasses: count($map),
        );
    }

    /**
     * Load XenForo itself. \XF::start() registers the autoloader and the alias resolver and
     * connects to nothing: the database is reached lazily, and nothing here asks for it.
     */
    private function boot(): void
    {
        if (! class_exists(\XF::class, false)) {
            require_once $this->root . '/src/XF.php';
        }

        \XF::start($this->root);
    }

    /**
     * Every class the forum aliases, from the class files under src/XF and the add-ons - an
     * add-on that has adopted the suffixed names is aliased the same way as core.
     *
     * @return array<string, string> alias => class
     */
    private function aliases(): array
    {
        $aliases = [];
        foreach ($this->classFiles() as $class => $file) {
            $alias = \XF::getAliasForClass($class);
            if ($alias !== $class) {
                $aliases[$alias] = $class;
                $this->files[$class] = $file;
            }
        }
        ksort($aliases);

        return $aliases;
    }

    /**
     * The class each PHP file under src/XF and src/addons would declare by its path, with the
     * directories that hold no add-on classes skipped.
     *
     * @return iterable<string, string> class => file
     */
    private function classFiles(): iterable
    {
        foreach (['/src/XF' => 'XF\\', '/src/addons' => ''] as $dir => $prefix) {
            $base = $this->root . $dir;
            if (! is_dir($base)) {
                continue;
            }

            /** @var iterable<string, \SplFileInfo> $files */
            $files = new RecursiveIteratorIterator(new RecursiveCallbackFilterIterator(
                new RecursiveDirectoryIterator($base, FilesystemIterator::SKIP_DOTS),
                fn (\SplFileInfo $file): bool => ! ($file->isDir() && in_array($file->getFilename(), self::SKIPPED, true)),
            ));

            foreach ($files as $file) {
                if ($file->getExtension() !== 'php') {
                    continue;
                }

                $relative = substr($file->getPathname(), strlen($base) + 1, -4);

                yield $prefix . str_replace('/', '\\', $relative) => $file->getPathname();
            }
        }
    }

    /** @return list<string> */
    private function extensionFiles(): array
    {
        $files = [
            ...(glob($this->root . '/src/addons/*/_data/class_extensions.xml') ?: []),
            ...(glob($this->root . '/src/addons/*/*/_data/class_extensions.xml') ?: []),
        ];
        sort($files);

        return $files;
    }

    /**
     * How the class is declared, read from its file rather than by loading it: `class`,
     * `abstract class` or `interface`. Null when the file declares no such type, or declares a
     * trait or an enum, which cannot be extended by a stub.
     */
    private function shape(string $class): ?string
    {
        $file = $this->files[$class] ?? null;
        if ($file === null) {
            return null;
        }

        $short = substr($class, (int) strrpos($class, '\\') + 1);
        $source = (string) file_get_contents($file);

        if (preg_match('/^\s*(?:(?:abstract|final|readonly)\s+)*(class|interface|trait|enum)\s+' . preg_quote($short, '/') . '\b/m', $source, $m) !== 1) {
            return null;
        }

        return match ($m[1]) {
            'class' => str_contains($m[0], 'abstract') ? 'abstract class' : 'class',
            'interface' => 'interface',
            default => null,
        };
    }

    private static function declarable(string $name): bool
    {
        return preg_match('/^[A-Za-z_\x80-\xff][A-Za-z0-9_\x80-\xff]*$/', $name) === 1
            && ! in_array(strtolower($name), self::RESERVED, true);
    }

    /**
     * Stated in UTC and labelled, so the header cannot be a day out from the clock on the
     * wall - PHP's CLI timezone is whatever php.ini says, which is not necessarily the box's.
     */
    private function now(): string
    {
        return (new DateTimeImmutable('now', new DateTimeZone('UTC')))->format('Y-m-d H:i') . ' UTC';
    }

    private function write(string $path, string $contents): void
    {
        if (@file_put_contents($path, $contents) === false) {
            throw new RuntimeException(sprintf('Could not write %s.', $path));
        }
    }
}
